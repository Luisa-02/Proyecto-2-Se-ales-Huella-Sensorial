def prep_audio(path):
    x, fs = sf.read(path, always_2d=True, dtype="float64")
    qc = dict(clip_frac=float(np.mean(np.abs(x) >= 0.999)), n_nan=int(np.isnan(x).sum()), canales=int(x.shape[1]))
    mono = x.mean(axis=1)
    mono = mono - mono.mean()
    return mono, fs, qc

def envelope(x, fs, n=2000):
    m = len(x) // n * n
    b = x[:m].reshape(n, -1)
    return (np.arange(n) + .5) * m / n / fs, b.min(1), b.max(1)

