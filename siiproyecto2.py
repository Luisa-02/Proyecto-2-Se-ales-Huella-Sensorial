def design_filters(fs):
    nyq = fs / 2
    assert FSTOP[1] < nyq, "FSTOP[1] debe ser < Nyquist"
    width = min(BAND[0] - FSTOP[0], FSTOP[1] - BAND[1]) / nyq
    N, beta = sg.kaiserord(RS, width)
    N = int(N) | 1                                   # longitud impar (Tipo I, fase lineal)
    h = sg.firwin(N, list(BAND), window=("kaiser", beta), pass_zero=False, fs=fs)
    n_ell, wn = sg.ellipord(list(BAND), list(FSTOP), RP, RS, fs=fs)
    sos = sg.ellip(n_ell, RP, RS, wn, btype="bandpass", output="sos", fs=fs)
    return dict(h=h, sos=sos, N=N, beta=float(beta), n_iir=int(n_ell), fs=fs)

def apply_fir(x, h):  # salida causal idéntica a la convolución directa, calculada por FFT (más rápida)
    return sg.oaconvolve(x, h, mode="full")[:len(x)]

def apply_iir(x, sos):
    return sg.sosfilt(sos, x)

