def spectro(ax, x, fs, nperseg, vmin, vmax, ylim=(0, 10000)):
    f_, t_, S = sg.spectrogram(x, fs, window="hann", nperseg=nperseg, noverlap=nperseg // 2, scaling="density", mode="psd")
