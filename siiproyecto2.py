def _natkey(p):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", str(p))]

def _listar(exts):
    out = []
    for p in DATA_DIR.rglob("*"):
        rel = p.relative_to(DATA_DIR)
        if p.is_file() and p.suffix.lower() in exts and not any(part.startswith((".", "__")) for part in rel.parts):
            out.append(p)
    return sorted(out, key=lambda p: _natkey(p.relative_to(DATA_DIR)))

def _nombre_sitio(p):
    parts = [x for x in p.relative_to(DATA_DIR).parts[:-1] if x.lower() not in MODALITY_DIRS]
    if parts: return parts[0]                                   # subcarpeta = sitio
    return re.sub(r"[\s_\-\.]*\d+$", "", p.stem).strip() or p.stem   # 'lago_3.wav' -> 'lago'

def construir_mapeo():
    A, I = _listar(AUDIO_IN), _listar(IMG_IN)
    assert A and I, f"No encontré audios ({len(A)}) o imágenes ({len(I)}) en {DATA_DIR}"
    sitios_a, sitios_i = defaultdict(list), defaultdict(list)
    for p in A: sitios_a[_nombre_sitio(p)].append(p)
    for p in I: sitios_i[_nombre_sitio(p)].append(p)
    nombres = sorted(set(sitios_a) | set(sitios_i), key=_natkey)
    codigos = {n: f"L{i:02d}" for i, n in enumerate(nombres, 1)}
    filas = []
    for n in nombres:
        a, i = sitios_a.get(n, []), sitios_i.get(n, [])
        sa = {p.stem.lower(): p for p in a}; si = {p.stem.lower(): p for p in i}
        if set(sa) == set(si) and len(sa) == len(a):
            pares = [(sa[k], si[k], False) for k in sorted(sa, key=_natkey)]
        elif len(a) == len(i):
            print(f"⚠️  {n}: nombres de audio/imagen no coinciden → emparejados POR ORDEN. Verifica mapeo_archivos.csv")
            pares = [(x, y, True) for x, y in zip(a, i)]
        else:
            comunes = sorted(set(sa) & set(si), key=_natkey)
            print(f"⚠️  {n}: {len(a)} audios y {len(i)} imágenes; solo uso los {len(comunes)} con el mismo nombre")
            pares = [(sa[k], si[k], False) for k in comunes]
        for pos, (pa, pi, por_orden) in enumerate(pares):
            m = _pat_std.match(pa.stem)
            filas.append(dict(sitio_codigo=codigos[n], sitio_nombre=n, sesion=int(m.group(2)) if m else np.nan,
                              repeticion=int(m.group(3)) if m else np.nan, ruta_audio=str(pa.relative_to(DATA_DIR)),
                              ruta_imagen=str(pi.relative_to(DATA_DIR)), emparejado_por_orden=por_orden, _pos=pos))
    df = pd.DataFrame(filas)
    # Asignación automática de sesión/repetición (mitad y mitad por orden de nombre) donde no vengan en el nombre
    for cod, g in df.groupby("sitio_codigo"):
        n = len(g); mitad = n // 2
        for k, idx in enumerate(g.index):
            if pd.isna(df.loc[idx, "sesion"]):
                df.loc[idx, "sesion"] = 1 if k < mitad else 2
                df.loc[idx, "repeticion"] = k + 1 if k < mitad else k - mitad + 1
    df["sesion"], df["repeticion"] = df["sesion"].astype(int), df["repeticion"].astype(int)
    df["id_par"] = [pair_id(s, a, r) for s, a, r in zip(df.sitio_codigo, df.sesion, df.repeticion)]
    return df.drop(columns="_pos")[["id_par", "sitio_codigo", "sitio_nombre", "sesion", "repeticion", "ruta_audio", "ruta_imagen", "emparejado_por_orden"]]

