class NearestCentroid:
    def fit(self, X, y):
        self.mu = X.mean(0); sd = X.std(0, ddof=1)
        self.zero_var = ~np.isfinite(sd) | (sd == 0)
        sd[self.zero_var] = 1.0; self.sd = sd
        Z = (X - self.mu) / self.sd; self.classes = sorted(set(y)); y = np.asarray(y)
        self.cent = np.vstack([Z[y == c].mean(0) for c in self.classes]); return self
    def dist2(self, X):                       # distancia² media por variable
        Z = (X - self.mu) / self.sd
        return ((Z[:, None, :] - self.cent[None, :, :])**2).mean(-1)

