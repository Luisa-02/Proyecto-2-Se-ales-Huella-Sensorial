def acoustic_descriptors(x, fs):
    f_, p = welch_psd(x, fs)
    msk = (f_ >= BAND[0]) & (f_ < BAND[1])
    fb, pb = f_[msk], p[msk]
    tot = pb.sum()
    d = {"rms": float(np.sqrt(np.mean(x**2)))}
    if tot <= 1e-30:                                   # silencio digital
        d.update({n: np.nan for n in A_NAMES[1:]}); return d
    pn = pb / tot
    nz = pn[pn > 0]
    d["centroide_hz"] = float(np.sum(fb * pn))
    d["entropia"] = float(-np.sum(nz * np.log2(nz)) / np.log2(len(pn)))
    for i, (lo, hi) in enumerate(BANDS3, 1):
        d[f"frac_b{i}"] = float(p[(f_ >= lo) & (f_ < hi)].sum() / tot)
    return d

