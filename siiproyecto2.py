def prep_image(path):
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    W, H = img.size; side = min(W, H)
    left, top = (W - side) // 2, (H - side) // 2
    crop = img.crop((left, top, left + side, top + side))
    small = crop.resize((IMG_SIZE, IMG_SIZE), Image.LANCZOS)
    info = dict(ancho=W, alto=H, recorte=(left, top, left + side, top + side), escala=IMG_SIZE / side)
    return np.asarray(small, dtype=np.float64) / 255.0, info, img

def gray_of(rgb):
    return 0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2]

def gauss_kernel(size=5, sigma=1.0):
    ax = np.arange(size) - size // 2
    g = np.exp(-ax**2 / (2 * sigma**2)); k = np.outer(g, g)
    return k / k.sum()

K_SMOOTH = gauss_kernel(5, 1.0)
K_SOBEL_X = np.array([[-1, 0, 1], [-2, 0, 2], [-1, 0, 1]], float)
K_SOBEL_Y = K_SOBEL_X.T

def conv2(img, k):
    return sg.convolve2d(img, k, mode="same", boundary="symm")

def grad_mag(g):
    return np.hypot(conv2(g, K_SOBEL_X), conv2(g, K_SOBEL_Y))

_win2d = np.outer(np.hanning(IMG_SIZE), np.hanning(IMG_SIZE))
_fx = np.fft.fftshift(np.fft.fftfreq(IMG_SIZE))
_R = np.hypot(*np.meshgrid(_fx, _fx))
MASK_LOW = (_R > 0) & (_R < R_SPLIT)
MASK_HIGH = (_R >= R_SPLIT) & (_R <= 0.5)

def fft2_power(g, remove_mean=True):
    g0 = g - g.mean() if remove_mean else g
    F = np.fft.fftshift(np.fft.fft2(g0 * _win2d))
    return np.abs(F)**2 / np.sum(_win2d**2)       # ≈ varianza por bin para ruido blanco

def radial_fracs(P):
    lo, hi = P[MASK_LOW].sum(), P[MASK_HIGH].sum()
    return lo / (lo + hi), hi / (lo + hi)

def glcm_props(g):
    q = np.clip(np.round(np.clip(g, 0, 1) * (GLCM_LEVELS - 1)), 0, GLCM_LEVELS - 1).astype(np.uint8)
